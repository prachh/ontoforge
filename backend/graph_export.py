"""Hand the knowledge graph to external graph tools.

GraphXR (Kineviz) is a hosted app without an embeddable library, so it gets a download: nodes.csv and edges.csv
(one row per node or link, with a category column GraphXR maps to node types) plus a README with the import steps.
Graphistry renders very large graphs on a GPU server: the graph is uploaded with the official `graphistry` client
(optional dependency, requirements-graphistry.txt) to the server configured in the environment, and the returned
link opens the visualisation. Nothing is uploaded without explicit confirmation.
"""
import csv
import io
import json
import os
import re
import zipfile
from collections import defaultdict
from xml.sax.saxutils import escape, quoteattr

from . import store as s

SCOPES = ('domain', 'code', 'both')


def graph_tables(snapshot, ont, scope):
    """Nodes and edges as plain rows for the domain ontology, the code graph, or both joined by concept→code mappings."""
    if scope not in SCOPES: raise ValueError('Scope must be domain, code or both')
    nodes, edges = [], []
    domain = [c for c in ont['concepts'] if c['layer'] == 'domain'] if scope in ('domain', 'both') else []
    if domain:
        rules = {}
        for r in ont.get('rules', []): rules[r['concept']] = rules.get(r['concept'], 0) + 1
        ids = {c['id'] for c in domain}
        for c in domain:
            nodes.append({'id': c['id'], 'label': c['name'], 'category': 'Concept', 'layer': 'domain', 'kind': 'Abstract concept' if c.get('abstract') else 'Concept',
                          'description': c.get('description', ''), 'rules': rules.get(c['id'], 0), 'properties': len(c.get('properties', [])), 'path': ''})
            if c.get('parent') in ids and c['parent'] != c['id']: edges.append({'source': c['id'], 'target': c['parent'], 'relationship': 'is a', 'kind': 'is_a'})
        for r in ont.get('relationships', []):
            for a in r.get('source_types', []):
                for b in r.get('target_types', []):
                    if a in ids and b in ids and a != b: edges.append({'source': a, 'target': b, 'relationship': r.get('label') or r['id'], 'kind': r.get('kind', 'relationship')})
    if scope in ('code', 'both'):
        with s.connect() as c:
            known = set()
            for id, name, kind, path in c.execute("SELECT id,name,type,json_extract(data,'$.path') FROM entities WHERE snapshot=?", (snapshot['id'],)):
                known.add(id); nodes.append({'id': id, 'label': name, 'category': kind, 'layer': 'code', 'kind': kind, 'description': '', 'rules': 0, 'properties': 0, 'path': path or ''})
            for src, tgt, kind in c.execute('SELECT source,target,type FROM edges WHERE snapshot=?', (snapshot['id'],)):
                if src in known and tgt in known and src != tgt: edges.append({'source': src, 'target': tgt, 'relationship': kind, 'kind': kind})
        if scope == 'both':
            concept_ids = {c['id'] for c in domain}
            for m in s.records('mapping', snapshot['source_id'], snapshot['id']):
                if m.get('concept_id') in concept_ids and m.get('entity_id') in known and m.get('status') != 'rejected':
                    edges.append({'source': m['concept_id'], 'target': m['entity_id'], 'relationship': 'implemented by', 'kind': 'evidence'})
    seen = set(); unique = []
    for e in edges:
        k = (e['source'], e['target'], e['relationship'])
        if k not in seen: seen.add(k); unique.append(e)
    return nodes, unique


def csv_text(rows, fields):
    out = io.StringIO(); w = csv.DictWriter(out, fieldnames=fields, extrasaction='ignore'); w.writeheader(); w.writerows(rows)
    return out.getvalue()

NODE_FIELDS = ['id', 'label', 'category', 'layer', 'kind', 'description', 'rules', 'properties', 'path']
EDGE_FIELDS = ['source', 'target', 'relationship', 'kind']

GRAPHXR_README = """Knowledge graph export for Kineviz GraphXR ({title}, {scope} scope)

Files
  nodes.csv  one row per node: id, label, category (node type), layer (domain or code), kind, description, rules, properties, path
  edges.csv  one row per link: source and target (node ids), relationship (link label), kind

Import into GraphXR
  1. Open a project in GraphXR and choose Import (or drag the files onto the canvas).
  2. Import nodes.csv first: use `id` as the node key, `category` as the node category and `label` as the caption.
  3. Import edges.csv as relationships: source column `source`, target column `target`, relationship type `relationship`
     (they refer to the node ids from step 1).
  4. Use GraphXR's 3D layouts, category colouring and filters; `layer` separates the domain ontology from the code graph
     and `rules` gives the number of business rules on each concept.

{nodes} nodes, {edges} edges. Generated by OntoForge (https://github.com/prachh/ontoforge).
"""


def graphxr_zip(snapshot, ont, scope, title):
    nodes, edges = graph_tables(snapshot, ont, scope)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('nodes.csv', '﻿' + csv_text(nodes, NODE_FIELDS))
        z.writestr('edges.csv', '﻿' + csv_text(edges, EDGE_FIELDS))
        z.writestr('README.txt', GRAPHXR_README.format(title=title, scope=scope, nodes=len(nodes), edges=len(edges)))
        z.writestr('graph.json', json.dumps({'nodes': nodes, 'edges': edges}, ensure_ascii=False))
    return buf.getvalue(), len(nodes), len(edges)


# ---- Graphistry ----
def graphistry_config():
    """Server and credentials from the environment: a personal key (preferred) or a username and password."""
    server = os.getenv('GRAPHISTRY_SERVER', 'hub.graphistry.com').strip()
    key_id, secret = os.getenv('GRAPHISTRY_PERSONAL_KEY_ID', '').strip(), os.getenv('GRAPHISTRY_PERSONAL_KEY_SECRET', '').strip()
    user, password = os.getenv('GRAPHISTRY_USERNAME', '').strip(), os.getenv('GRAPHISTRY_PASSWORD', '').strip()
    try:
        import graphistry  # noqa: F401
        installed = True
    except ImportError:
        installed = False
    auth = 'personal key' if key_id and secret else 'username and password' if user and password else None
    error = None if installed and auth else ('The graphistry package is not installed: pip install -r requirements-graphistry.txt' if not installed
                                             else 'Set GRAPHISTRY_PERSONAL_KEY_ID and GRAPHISTRY_PERSONAL_KEY_SECRET (or GRAPHISTRY_USERNAME and GRAPHISTRY_PASSWORD) in .env, and GRAPHISTRY_SERVER for a self-hosted server')
    return {'server': server, 'installed': installed, 'auth': auth, 'configured': error is None, 'error': error,
            '_creds': {'personal_key_id': key_id, 'personal_key_secret': secret} if key_id and secret else {'username': user, 'password': password}}


def graphistry_upload(snapshot, ont, scope, title):
    """Upload the graph and return the Graphistry link. Colours follow the node category."""
    cfg = graphistry_config()
    if not cfg['configured']: raise ValueError(cfg['error'])
    import graphistry
    import pandas as pd
    nodes, edges = graph_tables(snapshot, ont, scope)
    if not nodes: raise ValueError('There is nothing to upload for this scope')
    client = graphistry.client()
    try:
        client.register(api=3, server=cfg['server'], protocol='https', **cfg['_creds'])
        plotter = (client.edges(pd.DataFrame(edges, columns=EDGE_FIELDS), 'source', 'target').nodes(pd.DataFrame(nodes, columns=NODE_FIELDS), 'id')
                   .bind(point_title='label', point_label='label', edge_title='relationship', edge_label='relationship')
                   .encode_point_color('category', as_categorical=True))
        url = plotter.plot(render='url', name=f'{title} · {scope}', description='Exported from OntoForge')
    except Exception as e:  # the client raises plain exceptions for auth, network and server errors
        raise ValueError(f'Graphistry upload failed: {str(e)[:300]}') from None
    return {'url': url, 'nodes': len(nodes), 'edges': len(edges), 'server': cfg['server']}


# ---- Files for desktop graph tools, Neo4j and docs ----

FILE_FORMATS = {'graphml': ('graphml', 'application/graphml+xml'), 'gexf': ('gexf', 'application/gexf+xml'), 'neo4j': ('zip', 'application/zip'), 'mermaid': ('md', 'text/markdown; charset=utf-8')}
NODE_ATTRS = [('label', 'string'), ('category', 'string'), ('layer', 'string'), ('kind', 'string'), ('description', 'string'), ('rules', 'int'), ('properties', 'int'), ('path', 'string')]


def graphml(nodes, edges, title):
    """GraphML for yEd, Gephi, Cytoscape desktop and NetworkX."""
    out = ['<?xml version="1.0" encoding="UTF-8"?>', '<graphml xmlns="http://graphml.graphdrawing.org/xmlns">']
    for name, typ in NODE_ATTRS: out.append(f'  <key id="n_{name}" for="node" attr.name="{name}" attr.type="{typ}"/>')
    out += ['  <key id="e_relationship" for="edge" attr.name="relationship" attr.type="string"/>', '  <key id="e_kind" for="edge" attr.name="kind" attr.type="string"/>',
            f'  <graph id={quoteattr(title)} edgedefault="directed">']
    for n in nodes:
        out.append(f'    <node id={quoteattr(n["id"])}>' + ''.join(f'<data key="n_{k}">{escape(str(n.get(k, "")))}</data>' for k, _ in NODE_ATTRS) + '</node>')
    for i, e in enumerate(edges):
        out.append(f'    <edge id="e{i}" source={quoteattr(e["source"])} target={quoteattr(e["target"])}><data key="e_relationship">{escape(e["relationship"])}</data><data key="e_kind">{escape(e["kind"])}</data></edge>')
    out += ['  </graph>', '</graphml>']
    return '\n'.join(out)


def gexf(nodes, edges, title):
    """GEXF 1.3 for Gephi and Gephi Lite (node attributes become filters and partitions)."""
    out = ['<?xml version="1.0" encoding="UTF-8"?>', '<gexf xmlns="http://gexf.net/1.3" version="1.3">', f'  <meta><creator>OntoForge</creator><description>{escape(title)}</description></meta>',
           '  <graph defaultedgetype="directed" mode="static">', '    <attributes class="node">']
    attrs = [a for a in NODE_ATTRS if a[0] != 'label']
    out += [f'      <attribute id="{i}" title="{name}" type="{"integer" if typ == "int" else "string"}"/>' for i, (name, typ) in enumerate(attrs)]
    out += ['    </attributes>', '    <attributes class="edge"><attribute id="r" title="relationship" type="string"/><attribute id="k" title="kind" type="string"/></attributes>', '    <nodes>']
    for n in nodes:
        out.append(f'      <node id={quoteattr(n["id"])} label={quoteattr(str(n["label"]))}><attvalues>' + ''.join(f'<attvalue for="{i}" value={quoteattr(str(n.get(name, "")))}/>' for i, (name, _) in enumerate(attrs)) + '</attvalues></node>')
    out.append('    </nodes>\n    <edges>')
    for i, e in enumerate(edges):
        out.append(f'      <edge id="{i}" source={quoteattr(e["source"])} target={quoteattr(e["target"])} label={quoteattr(e["relationship"])}><attvalues><attvalue for="r" value={quoteattr(e["relationship"])}/><attvalue for="k" value={quoteattr(e["kind"])}/></attvalues></edge>')
    out += ['    </edges>', '  </graph>', '</gexf>']
    return '\n'.join(out)


def neo_label(text):
    word = re.sub(r'[^A-Za-z0-9]+', ' ', str(text)).title().replace(' ', '')
    return word if word and word[0].isalpha() else 'Node' + word

def neo_type(text):
    word = re.sub(r'[^A-Za-z0-9]+', '_', str(text)).strip('_').upper()
    return word if word and word[0].isalpha() else 'REL_' + word

NEO4J_README = """Neo4j import ({title}, {scope} scope): {nodes} nodes, {edges} relationships

Neo4j Desktop or Aura with LOAD CSV
  1. Copy nodes.csv and relationships.csv into the database's import folder (Desktop: ... > Open folder > Import).
  2. Run import.cypher in Neo4j Browser (it creates a uniqueness constraint, then loads nodes and relationships).
  3. Explore in Bloom: search "Concept", "Class" or a name; the category is the node label and `layer` separates domain and code.

neo4j-admin (empty database, fastest)
  neo4j-admin database import full --nodes=nodes-admin.csv --relationships=relationships-admin.csv neo4j
"""


def neo4j_zip(nodes, edges, title, scope):
    """CSV + Cypher for LOAD CSV, and header-annotated CSV for neo4j-admin import."""
    for n in nodes: n['neo_label'] = neo_label(n['category'])
    for e in edges: e['neo_type'] = neo_type(e['kind'] if e['kind'] not in ('link', 'relationship', 'semantic') else e['relationship'])
    labels = sorted({n['neo_label'] for n in nodes})
    cypher = ['// Run in Neo4j Browser (Neo4j 5) after copying nodes.csv and relationships.csv to the import folder. No plugins needed.',
              'CREATE CONSTRAINT node_id IF NOT EXISTS FOR (n:Node) REQUIRE n.id IS UNIQUE;', '',
              "LOAD CSV WITH HEADERS FROM 'file:///nodes.csv' AS row",
              'MERGE (n:Node {id: row.id})',
              'SET n.name = row.label, n.category = row.category, n.layer = row.layer, n.kind = row.kind, n.description = row.description,',
              '    n.rules = toInteger(row.rules), n.properties = toInteger(row.properties), n.path = row.path;', '',
              '// Each category becomes a label (Concept, Class, Function…) so Bloom and Cypher can use it.']
    cypher += [f"MATCH (n:Node) WHERE n.category = {json.dumps(next(x['category'] for x in nodes if x['neo_label'] == l))} SET n:{l};" for l in labels]
    cypher += ['', '// One statement per relationship type (Cypher cannot take a relationship type from data).']
    cypher += [f"LOAD CSV WITH HEADERS FROM 'file:///relationships.csv' AS row WITH row WHERE row.neo_type = '{t}'\nMATCH (a:Node {{id: row.source}}), (b:Node {{id: row.target}})\nMERGE (a)-[r:{t} {{name: row.relationship}}]->(b) SET r.kind = row.kind;"
               for t in sorted({e['neo_type'] for e in edges})]
    admin_nodes = [{'id:ID': n['id'], 'name': n['label'], ':LABEL': 'Node;' + n['neo_label'], 'category': n['category'], 'layer': n['layer'], 'kind': n['kind'], 'description': n['description'],
                    'rules:int': n['rules'], 'properties:int': n['properties'], 'path': n['path']} for n in nodes]
    admin_rels = [{':START_ID': e['source'], ':END_ID': e['target'], ':TYPE': e['neo_type'], 'name': e['relationship'], 'kind': e['kind']} for e in edges]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('nodes.csv', csv_text(nodes, NODE_FIELDS + ['neo_label']))
        z.writestr('relationships.csv', csv_text(edges, EDGE_FIELDS + ['neo_type']))
        z.writestr('import.cypher', '\n'.join(cypher) + '\n')
        z.writestr('nodes-admin.csv', csv_text(admin_nodes, list(admin_nodes[0]) if admin_nodes else ['id:ID']))
        z.writestr('relationships-admin.csv', csv_text(admin_rels, list(admin_rels[0]) if admin_rels else [':START_ID', ':END_ID', ':TYPE']))
        z.writestr('README.txt', NEO4J_README.format(title=title, scope=scope, nodes=len(nodes), edges=len(edges)))
    return buf.getvalue()


def mermaid(ont, title, module=None, limit=60):
    """A Mermaid class diagram of the domain ontology: classes with fields, inheritance, links and child tables."""
    domain = [c for c in ont['concepts'] if c['layer'] == 'domain']
    if module: domain = [c for c in domain if module.lower() in ' '.join([c.get('module') or '', c['name']]).lower()]
    degree = defaultdict(int)
    for r in ont.get('relationships', []):
        for a in r.get('source_types', []): degree[a] += 1
        for b in r.get('target_types', []): degree[b] += 1
    shown = sorted(domain, key=lambda c: -degree[c['id']])[:limit]; ids = {c['id'] for c in shown}
    mid = lambda c: 'C_' + re.sub(r'[^A-Za-z0-9_]', '_', c['name'])
    byid = {c['id']: c for c in shown}
    lines = ['classDiagram', '  direction LR']
    for c in shown:
        fields = [p for p in c.get('properties', []) if p.get('fieldtype') not in ('Link', 'Table', 'Table MultiSelect')][:8]
        body = ''.join(f"\n    +{re.sub(r'[^A-Za-z0-9_]', '_', p['name'])} {re.sub(r'[^A-Za-z0-9_]', '', p.get('fieldtype') or p.get('datatype') or 'string')}" for p in fields)
        lines.append(f'  class {mid(c)}["{c["name"].replace(chr(34), "")}"] {{{body}\n  }}')
        if c.get('abstract'): lines.append(f'  <<abstract>> {mid(c)}')
    for c in shown:
        if c.get('parent') in ids and c['parent'] != c['id']: lines.append(f'  {mid(byid[c["parent"]])} <|-- {mid(c)}')
    seen = set()
    for r in ont.get('relationships', []):
        for a in r.get('source_types', []):
            for b in r.get('target_types', []):
                if a in ids and b in ids and a != b and (a, b, r.get('label')) not in seen:
                    seen.add((a, b, r.get('label')))
                    arrow = '*--' if r.get('kind') == 'contains' else '-->'
                    label = re.sub(r'[^A-Za-z0-9_ ]', '', r.get('label') or '')[:40]
                    lines.append(f'  {mid(byid[a])} {arrow} {mid(byid[b])}' + (f' : {label}' if label else ''))
    note = f'{len(shown)} of {len(domain)} concepts (most connected first).' if len(domain) > len(shown) else f'{len(shown)} concepts.'
    return f'# {title}: domain class diagram\n\n{note} Paste into GitHub, GitLab, Notion, Confluence (Mermaid macro) or mermaid.live.\n\n```mermaid\n' + '\n'.join(lines) + '\n```\n'


def export_file(snapshot, ont, fmt, scope, title, module=None):
    if fmt not in FILE_FORMATS: raise ValueError('Format must be graphml, gexf, neo4j or mermaid')
    if fmt == 'mermaid': return mermaid(ont, title, module).encode()
    nodes, edges = graph_tables(snapshot, ont, scope)
    if fmt == 'graphml': return graphml(nodes, edges, title).encode()
    if fmt == 'gexf': return gexf(nodes, edges, title).encode()
    return neo4j_zip(nodes, edges, title, scope)
