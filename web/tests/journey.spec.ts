test('automatic approval keeps definitions and Studio protects unsaved changes',async({page,request})=>{
 const src=await (await request.post('/api/sources',{data:{kind:'sample',name:'Automatic approval verification'}})).json();
 await request.post('/api/sources/'+src.id+'/analyse',{data:{mode:'sample'}});
 await expect.poll(async()=>(await (await request.get('/api/state?source_id='+src.id)).json()).ontology?.status,{timeout:15000}).toBe('approved');
 const state=await (await request.get('/api/state?source_id='+src.id)).json();
 expect(state.ontology.concepts.filter((c:any)=>c.layer==='domain').map((c:any)=>c.name).sort()).toEqual(['Customer','Payment','Refund']);
 await page.addInitScript(id=>{localStorage.setItem('onto.source',id);localStorage.setItem('onto.page','Ontology Studio')},src.id);
 await page.goto('/');await expect(page.getByRole('heading',{name:'Ontology Studio',exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Description',exact:true}).fill('Unsaved draft definition');
 page.once('dialog',d=>d.dismiss());await page.getByRole('button',{name:'Overview',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Ontology Studio',exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Ontology rules JSON'}).fill(JSON.stringify([{id:'file-path',operator:'required',concept:'File',property:'path',interpretation:'Test explicit rule'}]));
 await page.getByRole('button',{name:'Save as new draft'}).click();await expect(page.getByText('Unsaved changes',{exact:true})).toHaveCount(0);
 const saved=await (await request.get('/api/state?source_id='+src.id)).json();expect(saved.ontology.rules[0].id).toBe('file-path');
});
